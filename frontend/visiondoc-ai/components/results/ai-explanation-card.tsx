import { ClipboardCheck, ListChecks, Sparkles, TriangleAlert } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Separator } from "@/components/ui/separator";
import type { AiExplanation } from "@/types";

export function AiExplanationCard({ explanation }: { explanation: AiExplanation }) {
  const { summary, findings, limitations, recommendation } = explanation;

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between pb-3">
        <div className="flex items-center gap-2">
          <Sparkles className="h-4 w-4 text-primary" />
          <CardTitle className="text-base">AI Explanation</CardTitle>
        </div>
        <Badge variant="secondary">Generated by Gemini</Badge>
      </CardHeader>
      <CardContent className="space-y-5">
        {/* Summary */}
        <p className="whitespace-pre-line text-sm leading-relaxed text-foreground">
          {summary}
        </p>

        {/* Key findings */}
        {findings && findings.length > 0 && (
          <div>
            <div className="mb-2 flex items-center gap-1.5">
              <ListChecks className="h-3.5 w-3.5 text-muted-foreground" />
              <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                Key Findings
              </p>
            </div>
            <ul className="space-y-1.5">
              {findings.map((finding, index) => (
                <li key={index} className="flex items-start gap-2 text-sm text-foreground">
                  <span className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-primary" />
                  <span className="leading-relaxed">{finding}</span>
                </li>
              ))}
            </ul>
          </div>
        )}

        <Separator />

        {/* Limitations */}
        {limitations && (
          <div className="flex gap-2.5 rounded-lg border border-amber-200 bg-amber-50 p-3">
            <TriangleAlert className="h-4 w-4 shrink-0 text-amber-600" />
            <div>
              <p className="text-xs font-semibold uppercase tracking-wide text-amber-800">
                Limitations
              </p>
              <p className="mt-1 text-sm leading-relaxed text-amber-900">
                {limitations}
              </p>
            </div>
          </div>
        )}

        {/* Recommendation */}
        {recommendation && (
          <div className="flex gap-2.5 rounded-lg border border-primary/20 bg-accent/50 p-3">
            <ClipboardCheck className="h-4 w-4 shrink-0 text-primary" />
            <div>
              <p className="text-xs font-semibold uppercase tracking-wide text-accent-foreground">
                Recommendation
              </p>
              <p className="mt-1 text-sm leading-relaxed text-foreground">
                {recommendation}
              </p>
            </div>
          </div>
        )}

        <p className="border-t border-border pt-3 text-xs text-muted-foreground">
          This explanation is AI-generated to aid understanding and does not
          constitute a medical diagnosis. Always consult a qualified
          radiologist or physician.
        </p>
      </CardContent>
    </Card>
  );
}
